#!/usr/bin/env python3
"""Write port/bios/bios_sine_table.inc, the 256-entry sine table that the
port's BgAffineSet and ObjAffineSet use (port/bios/bios_math.c).

Entry i is trunc(sin(2 * pi * i / 256) * 0x4000): the sine of i/256 of a full
turn in 1.14 fixed point, truncated toward zero. The GBA BIOS table has these
values (port-plan/community-reuse-audio-bios.md, section 2.2: computed against
two independent descriptions of it). The table is generated from the formula,
not copied from any BIOS. port/test/bios checks the committed file against
this script and against the C library's sin().

Usage (from the repository root):
    python3 -I port/bios/gen_sine_table.py > port/bios/bios_sine_table.inc
"""

import math
import sys


def entries():
    return [math.trunc(math.sin(2 * math.pi * i / 256) * 0x4000) for i in range(256)]


def main():
    out = sys.stdout
    out.write("/* Generated by port/bios/gen_sine_table.py. Do not edit.\n")
    out.write(" * Entry i = trunc(sin(2 * pi * i / 256) * 0x4000), i = 0..255. */\n")
    values = entries()
    for row in range(0, 256, 8):
        out.write("   " + "".join(" %6d," % v for v in values[row:row + 8]) + "\n")


if __name__ == "__main__":
    main()
