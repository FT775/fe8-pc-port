-- Scene viewer bot (coverage 12, scenes-i; port/test/inputs/watch/README-i.md): from a cleared
-- save, plays support conversations in the Extras menu's support viewer (Extras > Support
-- Conversation, src/uisupport.c), watching each with A at a human pace, and writes the keys it
-- pressed as a Gate 0 key file. Like route_bot.lua it reads game RAM to decide each tick's keys;
-- the key file is the product, and it replays open-loop.
--
--   GATE0_SRAM_IN=port/test/saves/sv_clear.sav VIEW_OUT=x.keys VIEW_PACE=fast \
--     MGBA_RUN_BP=<GBA_BP of port/test/Makefile> \
--     build/gate0/mgba_lua_run fireemblem8.gba port/test/oracle/scene_viewer.lua 400000
--
-- Environment:
--   VIEW_OUT    key file to write (required)
--   VIEW_PACE   fast (A held 2-4 ticks, 4-14 between) or slow (held 3-7, 40-120 between), as
--               route_bot.lua's ROUTE_WATCH; VIEW_SEED seeds its LCG (default 1)
--   VIEW_PLAN   the conversations, in order, on the viewer's unit pages: "P.R" plays partner row
--               P (0 = top) at rank R (1 C, 2 B, 3 A) of the page shown, "R" turns to the next
--               unit's page (the R button); default "0.1,0.2,0.3,1.1,R,0.1,2.1,R,0.2"
--   VIEW_TAIL   ticks to run after the plan's last conversation (default 300)
-- The tick rule is the capture's (route_lib.lua "Tick rules"), so it needs MGBA_RUN_BP.
-- The viewer lists only conversations the save's global block records: no bot save has one, so
-- the start is an edited save (port/test/tools/sram_support_edit.py, test coverage only).

local L = dofile(os.getenv("ROUTE_LIB") or "port/test/oracle/route_lib.lua")
local K = L.KEY
local outPath = assert(os.getenv("VIEW_OUT"), "VIEW_OUT is required")
local pace = os.getenv("VIEW_PACE") or "fast"
assert(pace == "fast" or pace == "slow", "VIEW_PACE must be fast or slow")
local seed = tonumber(os.getenv("VIEW_SEED") or "1")
local planSpec = os.getenv("VIEW_PLAN") or "0.1,0.2,0.3,1.1,R,0.1,2.1,R,0.2"
local tail = tonumber(os.getenv("VIEW_TAIL") or "300")

local SAVEMENU = 0x08A200B8          -- ProcScr_SaveMenu
local SM_MAIN = 0x080A9025           -- its main-menu key loop (main_select +0x2B, main_options +0x30)
local SM_EXTRA = 0x080A9B91          -- its Extras loop (extra_select +0x34, extra_options +0x32)
local LIST_KEYS = 0x080A15B1         -- SupportScreen_Loop_KeyHandler (the unit list)
local SUB = 0x08A19880               -- gProcScr_SupportUnitSubScreen (unk_39 +0x39: partner << 2 | rank - 1)
local SUB_KEYS = 0x080A2449          -- SupportSubScreen_Loop_KeyHandler

local plan = {}
for item in planSpec:gmatch("[^,]+") do
  if item == "R" then plan[#plan + 1] = { next = true }
  else
    local p, r = item:match("^(%d+)%.(%d)$")
    assert(p, "VIEW_PLAN: bad item " .. item)
    plan[#plan + 1] = { p = tonumber(p), r = tonumber(r) }
  end
end

local masks = { [1] = 0 }
local queue = {}
local tick = 0
local rn = seed & 0x7FFFFFFF
local step, played, doneAt, inEvent = 1, 0, nil, false
local wins, presses = {}, 0
local lastMoveSig, sameMoves = nil, 0

local function push(mask, hold, gap)
  for _ = 1, hold do queue[#queue + 1] = mask end
  for _ = 1, gap do queue[#queue + 1] = 0 end
end
local function rand(lo, hi)
  rn = (rn * 1103515245 + 12345) & 0x7FFFFFFF
  return lo + ((rn >> 8) % (hi - lo + 1))
end
local function note(a, b)
  local w = wins[#wins]
  if w and a <= w[2] + 300 and a >= w[1] then if b > w[2] then w[2] = b end else wins[#wins + 1] = { a, b } end
end
local function humanA()
  local hold, gap
  if pace == "fast" then hold, gap = rand(2, 4), rand(4, 14) else hold, gap = rand(3, 7), rand(40, 120) end
  presses = presses + 1
  note(tick, tick + hold + gap)
  push(K.A, hold, gap)
end
local function popcount(b) local n = 0; while b ~= 0 do n = n + (b & 1); b = b >> 1 end; return n end
local function go(cur, want) if cur < want then push(K.DOWN, 2, 10) elseif cur > want then push(K.UP, 2, 10) else push(K.A, 2, 20) end end

local function finish(reason)
  local f = assert(io.open(os.getenv("GATE0_SRAM_IN"), "rb"))
  local s = f:read(0x8000); f:close()
  local h = 0x811C9DC5
  for i = 1, #s do h = ((h ~ s:byte(i)) * 0x01000193) & 0xFFFFFFFF end
  local parts, n = {}, 0
  for _, w in ipairs(wins) do parts[#parts + 1] = w[1] .. "-" .. w[2]; n = n + w[2] - w[1] + 1 end
  local header = string.format(
    "# FE8 Gate 0 key file (format: port/test/README.md, \"Input file\").\n" ..
    "# Generated by port/test/oracle/scene_viewer.lua (VIEW_PACE=%s, VIEW_SEED=%d, VIEW_PLAN=%s, VIEW_TAIL=%d).\n" ..
    "# Start: boot both sides with GATE0_SRAM_IN=%s (the save's first 32 KiB: FNV-1a %08x).\n" ..
    "# How it was made and how to replay: port/test/inputs/watch/README-i.md.\n" ..
    "# %d ticks. Stop reason: %s\n#\n" ..
    "# Scenes watched (VIEW_PACE=%s, %d A presses, %d windows, %d ticks): %s\n",
    pace, seed, planSpec, tail, os.getenv("GATE0_SRAM_IN"):match("[^/]*$"), h, #masks, reason, pace, presses, #wins, n,
    table.concat(parts, ","))
  L.writeKeys(outPath, masks, header)
  print(string.format("scene_viewer: %s; %d ticks, %d conversations -> %s", reason, #masks, played, outPath))
  io.stdout:flush()
  os.exit(0)
end

local function decide()
  local procs = L.procs()
  local ev = L.findScript(procs, L.PROC.EventEngine)
  if ev then
    if not inEvent then inEvent = true; played = played + 1; print(string.format("[%d] conversation %d starts", tick, played)) end
    humanA()
    return
  end
  if inEvent then inEvent = false; print(string.format("[%d] conversation %d ends", tick, played)); if step > #plan then doneAt = tick end end
  local sm = L.findScript(procs, SAVEMENU)
  if sm and sm.idle == SM_MAIN then go(emu:read8(sm.addr + 0x2B), popcount(emu:read8(sm.addr + 0x30) & 0x1F)); return end
  if sm and sm.idle == SM_EXTRA then go(emu:read8(sm.addr + 0x34), popcount(emu:read8(sm.addr + 0x32) & 0x03)); return end
  if L.findIdle(procs, LIST_KEYS) then push(K.A, 2, 20); return end
  local sub = L.findScript(procs, SUB)
  if sub and sub.idle == SUB_KEYS then
    local it = plan[step]
    if not it then push(0, 0, 1); return end
    if it.next then push(K.R, 2, 10); step = step + 1; return end
    local v = emu:read8(sub.addr + 0x39)
    local p, r = (v >> 2) & 7, (v & 3) + 1
    local sig = step .. ":" .. v
    if sig == lastMoveSig then sameMoves = sameMoves + 1 else sameMoves = 0; lastMoveSig = sig end
    if sameMoves > 3 then print(string.format("[%d] plan item %d: the cursor does not move (row %d rank %d), skipped", tick, step, p, r)); step = step + 1; sameMoves = 0; return end
    if p < it.p then push(K.DOWN, 2, 10) elseif p > it.p then push(K.UP, 2, 10)
    elseif r < it.r then push(K.RIGHT, 2, 10) elseif r > it.r then push(K.LEFT, 2, 10)
    else
      print(string.format("[%d] plan item %d: unit %d, partner row %d, rank %d", tick, step, emu:read32(sub.addr + 0x2C), p, r))
      push(K.A, 2, 20); step = step + 1
    end
    return
  end
  if not sm and not sub then push(K.A, 1, 20); return end   -- the title screens
  push(0, 0, 1)
end

emu:setKeys(0)
L.onTick("capture", function() end, function()
  if doneAt and tick - doneAt >= tail then finish("the plan's conversations played") end
  if tick > 400000 then finish("tick limit") end
  if #queue == 0 then decide() end
  local m = table.remove(queue, 1) or 0
  masks[tick + 2] = m
  tick = tick + 1
  emu:setKeys(m)
end)
