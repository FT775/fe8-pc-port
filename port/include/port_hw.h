#ifndef GUARD_PORT_PORT_HW_H
#define GUARD_PORT_PORT_HW_H

/* Host-side hardware shim (port/hw). Port-only code, not compiled by agbcc. */

#include <stdint.h>

#define PORT_EWRAM_START 0x02000000u
#define PORT_IWRAM_START 0x03000000u
#define PORT_IO_START    0x04000000u
#define PORT_PLTT_START  0x05000000u
#define PORT_VRAM_START  0x06000000u
#define PORT_OAM_START   0x07000000u
#define PORT_ROM_START   0x08000000u
#define PORT_ROM_MAX     0x02000000u
#define PORT_SRAM_START  0x0E000000u

/* memory.c */
int PortMemInit(const char *romPath);
uint32_t PortRomSize(void);
/* 1 when addr is inside one of the GBA regions this run has (reserved by
   PortMemInit, or mapped by the ELF loader): the gaps between them are not. */
int PortMemInGbaMap(uint32_t addr);
/* What the ROM file at path is (the checks PortMemInit's load makes): the
   original FE8 (USA) ROM; not FE8 (USA) by its header (or not readable); the
   FE8 (USA) header with another size (a dump cut short) or another SHA-1 (a
   changed ROM). sha1: its SHA-1 in hex when the size was right, else "". */
enum { PORT_ROM_FE8, PORT_ROM_NOT_FE8, PORT_ROM_WRONG_SIZE, PORT_ROM_WRONG_SHA1 };
int PortRomFileKind(const char *path, char sha1[41]);

/* romreloc.c (table generated by port/tools/fixptr.py) */
void PortApplyRomRelocs(void);
uint32_t PortRomGbaWord(uint32_t site); /* the GBA's word at an aligned ROM address */

/* frame.c */
extern uint32_t gPortFrameCount;
extern uint32_t gPortFrameLimit;
extern volatile uint32_t gPortIrqDepth; /* nonzero inside a game IRQ handler */
void PortRunFrame(void);

/* pacer.c (frame pacing at 59.7275 Hz; the platform interface is port/platform.h) */
void PortPaceInit(int realtime);
void PortPaceFrame(void);
void PortPaceReport(void);

/* main_pc.c */
extern uint32_t gPortOnMainCalls;
void PortStubHit(const char *name, unsigned gbaAddr, unsigned *count);
void PortLog(const char *fmt, ...);
void PortExit(int code);
void PortSoftReset(void);

/* nullprobe.c: FE8PC_NULLPROBE=1, a diagnostic mode in which BIOS-area and
   NULL-page reads return the open-bus latch, integer division traps get the
   GBA libgcc result, and every site is recorded. With the variable unset
   every function returns at once (Init 0, OnFault 0, OnDivFault 0). */
int PortNullProbe_Init(void); /* 1 on, 0 off, -1 asked for but unavailable */
int PortNullProbe_Enabled(void);
int PortNullProbe_OnFault(void *ucontext, uint32_t addr); /* 1: handled, resume */
int PortNullProbe_OnDivFault(void *ucontext);             /* SIGFPE; 1: handled, resume */
void PortNullProbe_NoteDroppedWrite(uint32_t eip, uint32_t eipAfter, uint32_t addr);
void PortNullProbe_Dump(const char *why);

/* The command line: fe8pc [--save PATH | --save=PATH | --no-save] [settings] [--] [ROM]
   (main_pc.c lists the settings options).
   PortParseArgs fills args (rom and save NULL when not given) and returns 0,
   or returns -1 with *error set for a bad command line. port/win32 uses it to
   tell whether a ROM path was given. */
#define PORT_ARG_SETS 32
struct PortArgs
{
    const char *rom;
    const char *save;
    int noSave;
    /* --set KEY=VALUE and its short forms (--scale N, --fullscreen, --windowed,
       --seed X, --randomizer): settings-file lines for this run, applied over
       the settings file (port/reforged/reforged_settings.c, played builds) */
    const char *sets[PORT_ARG_SETS];
    int setCount;
};
int PortParseArgs(int argc, char **argv, struct PortArgs *args, const char **error);
/* The command line's settings (main_pc.c keeps them from PortParseArgs): how many,
   and each "KEY=VALUE". */
int PortArgSettingCount(void);
const char *PortArgSetting(int i);

/* save/savefile_pc.c: the player's save file (raw 32 KiB SRAM image, as mGBA's
   .sav). Init loads it into SRAM before AgbMain (0, or -1: stop the run);
   Frame writes it at the end of each frame step when SRAM changed; Flush
   writes it at exit. */
int PortSave_Init(const char *romPath, const char *savePath, int noSave);
void PortSave_Frame(void);
void PortSave_Flush(void);

#endif /* GUARD_PORT_PORT_HW_H */
